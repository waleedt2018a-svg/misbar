function isGenderMappedOptions(
  options: unknown
): options is Record<Gender, readonly string[]> {
  return typeof options === "object" && options !== null && "ذكر" in options && "أنثى" in options;
}

export function getStudentMajors(college: string, gender: Gender | "") {
  const options = studentColleges[college as keyof typeof studentColleges];

  if (!options) {
    return [];
  }

  if (Array.isArray(options)) {
    return [...options];
  }

  if (gender && isGenderMappedOptions(options)) {
    return [...options[gender]];
  }

  return [];
}
